function cm_data=Rainbow(m)

cm=[[181 187 232];...
    [202 181 224];...
    [219 176 211];...
    [229 173 194];...
    [232 174 176];...
    [227 177 160];...
    [216 183 149];...
    [199 189 146];...
    [180 194 150];...
    [161 199 161]];

cm=cm/255;

if nargin < 1
    cm_data = cm;
else
    hsv=rgb2hsv(cm);
    %hsv(153:end,1)=hsv(153:end,1)+1; % hardcoded
    cm_data=interp1(linspace(0,1,size(cm,1)),hsv,linspace(0,1,m));
    cm_data(cm_data(:,1)>1,1)=cm_data(cm_data(:,1)>1,1)-1;
    cm_data=hsv2rgb(cm_data);
  
end

end